import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { format, resolveConfig } from 'prettier';
import { parse } from 'yaml';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, '../..');
const pythonRoot = path.resolve(
    repositoryRoot,
    readOption('--python-root') ?? '../agentscope-python'
);
const outputPath = path.join(repositoryRoot, 'packages/agentscope/src/model/cards.generated.ts');

const sourceRoot = path.join(pythonRoot, 'src/agentscope');
const yamlPaths = (await walk(sourceRoot)).filter(filePath => filePath.endsWith('.yaml')).sort();

const records = [];
for (const yamlPath of yamlPaths) {
    const sourcePath = path.relative(pythonRoot, yamlPath).split(path.sep).join('/');
    const match = sourcePath.match(
        /^src\/agentscope\/(model|embedding|tts)\/_([^/]+)\/_(?:cosyvoice_)?models\/([^/]+)\.yaml$/
    );
    if (!match) throw new Error(`Unsupported model-card path: ${sourcePath}`);
    records.push({
        kind: match[1] === 'model' ? 'chat' : match[1],
        provider: match[2],
        sourcePath,
        config: parse(await readFile(yamlPath, 'utf8')),
    });
}

const source =
    `// Generated by scripts/parity/generate-model-cards.mjs. Do not edit manually.\n\n` +
    `import type { RawModelCardRecord } from './card';\n\n` +
    `export const MODEL_CARD_RECORDS = ${JSON.stringify(records, null, 4)} as const satisfies readonly RawModelCardRecord[];\n`;
const prettierOptions = (await resolveConfig(outputPath)) ?? {};
await writeFile(
    outputPath,
    await format(source, { ...prettierOptions, parser: 'typescript' }),
    'utf8'
);
process.stdout.write(`Generated ${records.length} model cards at ${outputPath}.\n`);

function readOption(name) {
    const index = process.argv.indexOf(name);
    return index >= 0 ? process.argv[index + 1] : undefined;
}

async function walk(directory) {
    const entries = await readdir(directory, { withFileTypes: true });
    const files = [];
    for (const entry of entries) {
        const entryPath = path.join(directory, entry.name);
        if (entry.isDirectory()) files.push(...(await walk(entryPath)));
        else files.push(entryPath);
    }
    return files;
}
